package pw.x4.ninety.data.persistence

class EntityMapper(
    private val secrets: SecretCodec,
) {
    fun toEntity(profile: PersistedProfile): ProfileEntity = ProfileEntity(
        id = profile.id,
        name = profile.name,
        type = profile.type,
        urlCiphertext = secrets.encrypt(profile.url),
        used = profile.used,
        total = profile.total,
        expire = profile.expire,
        updatedAt = profile.updatedAt,
    )

    fun fromEntity(profile: ProfileEntity): PersistedProfile = PersistedProfile(
        id = profile.id,
        name = profile.name,
        type = profile.type,
        url = secrets.decrypt(profile.urlCiphertext),
        used = profile.used,
        total = profile.total,
        expire = profile.expire,
        updatedAt = profile.updatedAt,
    )

    fun toEntity(node: PersistedNode): NodeEntity = NodeEntity(
        id = node.id,
        profileId = node.profileId,
        protocol = node.protocol,
        name = node.name,
        host = node.host,
        port = node.port,
        uuidCiphertext = secrets.encrypt(node.uuid),
        passwordCiphertext = secrets.encrypt(node.password),
        method = node.method,
        cipher = node.cipher,
        alterId = node.alterId,
        security = node.security,
        transport = node.transport,
        flow = node.flow,
        sni = node.sni,
        fingerprint = node.fingerprint,
        publicKey = node.publicKey,
        shortId = node.shortId,
        alpn = node.alpn,
        path = node.path,
        hostHeader = node.hostHeader,
        serviceName = node.serviceName,
        mode = node.mode,
        extra = node.extra,
        upMbps = node.upMbps,
        downMbps = node.downMbps,
        obfs = node.obfs,
        obfsPasswordCiphertext = secrets.encrypt(node.obfsPassword),
        certificatePublicKeySha256 = node.certificatePublicKeySha256,
        congestionControl = node.congestionControl,
        udpRelayMode = node.udpRelayMode,
        insecure = node.insecure,
        zeroRttHandshake = node.zeroRttHandshake,
        disableSni = node.disableSni,
        plugin = node.plugin,
        pluginOptions = node.pluginOptions,
        rawCiphertext = secrets.encrypt(node.raw),
        fromSubscription = node.fromSubscription,
    )

    fun fromEntity(node: NodeEntity): PersistedNode = PersistedNode(
        id = node.id,
        profileId = node.profileId,
        protocol = node.protocol,
        name = node.name,
        host = node.host,
        port = node.port,
        uuid = secrets.decrypt(node.uuidCiphertext),
        password = secrets.decrypt(node.passwordCiphertext),
        method = node.method,
        cipher = node.cipher,
        alterId = node.alterId,
        security = node.security,
        transport = node.transport,
        flow = node.flow,
        sni = node.sni,
        fingerprint = node.fingerprint,
        publicKey = node.publicKey,
        shortId = node.shortId,
        alpn = node.alpn,
        path = node.path,
        hostHeader = node.hostHeader,
        serviceName = node.serviceName,
        mode = node.mode,
        extra = node.extra,
        upMbps = node.upMbps,
        downMbps = node.downMbps,
        obfs = node.obfs,
        obfsPassword = secrets.decrypt(node.obfsPasswordCiphertext),
        certificatePublicKeySha256 = node.certificatePublicKeySha256,
        congestionControl = node.congestionControl,
        udpRelayMode = node.udpRelayMode,
        insecure = node.insecure,
        zeroRttHandshake = node.zeroRttHandshake,
        disableSni = node.disableSni,
        plugin = node.plugin,
        pluginOptions = node.pluginOptions,
        raw = secrets.decrypt(node.rawCiphertext),
        fromSubscription = node.fromSubscription,
    )
}
